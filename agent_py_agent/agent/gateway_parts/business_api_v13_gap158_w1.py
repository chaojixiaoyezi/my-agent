def _ready(call):
    return bool(getattr(call.services.host.config, 'openai_compat_gateway_enabled', False))


def _gateway(call):
    from ..business_spaces import gap158_w1_openai_compat as gateway
    from .business_api_v13 import v13_require_access

    v13_require_access(call)
    with ExitStack() as stack:
        provider = getattr(call.context, 'host_provider', None)
        host = provider(stack) if callable(provider) else call.context.host
        if host.home_paths.owner_id != call.owner_id:
            raise HostAPIError('RESOURCE_NOT_FOUND', 404)
        v13_require_access(call)
        options = {'request_id': call.request_id, 'admission_key': call.subject_id,
                   'quota_config': call.services.host.config}
        if call.action == 'llm.gateway.test':
            return gateway.test_gateway(host, call.params, **options)
        return gateway.execute(host, call.params, **options)


