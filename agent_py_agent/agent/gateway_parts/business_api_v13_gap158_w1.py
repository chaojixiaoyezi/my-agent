def install_actions():
    """W0 未预注册时在 HTTP 组合根接入同一注册器；不维护第二目录，也不接受 JSON 注册。"""
    from . import business_api_v13 as registry

    name = __name__
    with _INSTALL_LOCK:
        if name in registry.V13_SLICE_MODULES:
            return
        registry.V13_SLICE_MODULES = (*registry.V13_SLICE_MODULES, name)
        (registry._ACTIONS, registry.ALIASES, registry.V13_DEFS,
         registry.JOB_KINDS, registry.COLLECTIONS) = registry._load_registry()
