# LLM: ready只看当前宿主开关，不创建目录或把可用性当授权；读写仍走W0实时末核。
# 函数用途: 宣告本地集合动作是否具备基础服务。
def _store_ready(call):
    return bool(getattr(call.services.host.config, 'business_spaces_enabled', False))


# LLM: 成本必须有冻结usage读口，缺源不制造零消耗；此处不发查询或建状态。
# 函数用途: 检查成本查询所需的原生来源。
def _usage_ready(call):
    return _store_ready(call) and call.services.ready('usage.get')


# LLM: 异步执行复用W0的原任务端口条件；就绪检查不会派发模型工作。
# 函数用途: 检查规则转换的后台执行和任务观察入口。
def _jobs_ready(call):
    return (_store_ready(call)
            and callable(getattr(call.services.background, 'execute', None))
            and call.services.ready('tasks.get'))


