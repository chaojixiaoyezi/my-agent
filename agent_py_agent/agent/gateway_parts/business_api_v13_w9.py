# LLM: 读取就绪事实不取任何令牌、连接或写权限。
# 函数用途: 判断 owner 业务存储是否已开启。
def _store_ready(call):
    return bool(getattr(call.services.host.config, "business_spaces_enabled", False))


# LLM: provider 仅从宿主绑定取得；未绑定不发布对应动作。
# 函数用途: 判断已声明的外部适配器是否可用。
def _provider_ready(call, name):
    return _store_ready(call) and getattr(call.services.host, "business_v13_providers", {}).get(name) is not None


# LLM: 只读解析器不会发 HTTP。
# 函数用途: 报告 OAuth 交换适配器就绪情况。
def _oauth_ready(call):
    return _provider_ready(call, "oauth_http")


# LLM: 同步动作依赖真实 provider，不用空列表伪装同步完成。
# 函数用途: 报告情报同步适配器就绪情况。
def _intel_ready(call):
    return _provider_ready(call, "threat_intel")


# LLM: 当前没有内建 FIM 引擎，必须有宿主适配器。
# 函数用途: 报告 FIM 查询适配器就绪情况。
def _fim_ready(call):
    return _provider_ready(call, "osquery_fim")


# LLM: 模型输出只按 JSON 解码，正式 schema 仍由 W0 job runner 校验。
# 函数用途: 将诊断模型输出转成结构化结果。
def _finalize_diagnosis(text):
    value = json.loads(text)
    if not isinstance(value, dict):
        raise ValueError("JOB_RESULT_INVALID")
    return value


