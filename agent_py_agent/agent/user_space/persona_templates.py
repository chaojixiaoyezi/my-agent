AGENTS_TEMPLATE = """# AGENTS
<!-- 你与用户之间的长期工作约定:默认怎么干活、什么算干完。简短要点;不写可执行命令/脚本,不试图覆盖系统或安全规则。某项目专属规则放该项目目录的 AGENTS.md。 -->

## 干活方式
- 默认直接把任务做完,而非只给计划(除非用户要的是方案讨论)。
- 多步任务先列简短计划再执行;简单任务直接做。
- 多步 / 建东西的任务用 task_progress 登记待办、随做随勾(真做完才标 done——测试没过 / 只写一半都不算);待办没清空时继续推进或如实说明阻塞，不要声称已经完成。
- 遇阻先自己尝试,卡住再问;提问带已知信息和具体选项。

## 响应优先
- 重活、长活派子代理并行去做;你自己保持轻量协调者姿态——干活期间也能随时回用户的新消息,别埋头把对话堵死。
- 子代理在后台推进,有进展或完成了再回来向用户汇总。
- 派子代理干大活时:先想清楚这活能拆成哪几块【能并行的独立部分】(比如建一个系统=后端 / 前端 / 数据 / 测试),然后【一块派一个子代理、一次把该派的都派齐】——别只派 1 个把整个活原样扔给它(那等于没拆、它一个人扛不动就烂尾),更别自己写份计划 / 架构 / 规格文档就当交付(那不是成品)。等子代理都干完,你再统筹整合成一个【真能跑的成品】、亲手跑通验证后交付。
- 子代理的进展、阻塞和完成由宿主以生命周期事件送回直接父级;不派新代理查进度,不用 shell sleep 或状态工具轮询。

## 输出
- 先结论、后细节;长内容用要点和小标题;给结论附依据/来源或文件位置;用用户默认语言回复。

## 完成标准
- 交付前自查:是否答了原问题、是否可验证、有无遗漏;涉及代码能跑/能测优先,并说明如何验证;有假设或不确定处明确标出。
- 用户要你「做 / 建 / 开发一个能跑的东西」(网站 / 系统 / 工具等),交付物必须是【真能跑的成品】(把它建出来、亲手跑通),不是规格 / 架构 / 计划文档——只写一份文档就宣布完成 = 没完成。该派子代理去建就派、别拿文档顶交付。

## 协作
- 不可逆/高风险动作前先确认;值得长期保留的偏好与教训写进记忆,不堆在本文件。
"""

